REVIEW_TILE = 320


def run(command):
    print(">", " ".join(str(c) for c in command[:4]), "...")
    subprocess.run([str(c) for c in command], check=True, stdout=subprocess.DEVNULL)


def sha(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()[:16]


def built_file(name: str) -> Path:
    return BUILD / f"{TEXTURES[name][1]}.png"


def recorded() -> dict:
    """{name: (id, hash)} from the generated Vfx/Textures.luau."""
    if not LUAU.exists():
        return {}
    found = re.findall(r'(\w+) = \{ Id = "([^"]*)", Hash = "([0-9a-f]*)" \}', LUAU.read_text(encoding="utf-8"))
    return {name: (asset, digest) for name, asset, digest in found}


def write_luau(records: dict):
    lines = [
        "--!strict",
        "-- Textures: GENERATED by tools/vfx/textures.py; don't edit by hand. Each effect texture's uploaded id and the hash",
        "-- of the built file it was uploaded from (a rebuild that changes the hash needs a new upload). Vfx/Kit reads the",
        "-- ids; what each texture is, where it comes from and how it's laid out is in the tool's registry.",
        "",
        "return {",
    ]
    for name, (_, _, note) in TEXTURES.items():
        if name in records:
            asset, digest = records[name]
            lines.append(f'\t{name} = {{ Id = "{asset}", Hash = "{digest}" }}, -- {note}')
    lines += ["}", ""]
    LUAU.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", LUAU.relative_to(REPO))


def build(names):
    unknown = [n for n in names if n not in TEXTURES]
    assert not unknown, f"not in the registry: {unknown}"
    wanted = names or list(TEXTURES)
    BUILD.mkdir(parents=True, exist_ok=True)
    if any(TEXTURES[n][0] == "drawn" for n in wanted):
        run([sys.executable, DRAWN, BUILD])
    sprites = [TEXTURES[n][1] for n in wanted if TEXTURES[n][0] == "sprites"]
    if sprites:
        run([BLENDER, "-b", "--factory-startup", "--python", SPRITES, "--", BUILD, *sprites])
    review()


def review():
    """build/vfx/review.png: every built texture, numbered in registry order."""
    present = [name for name in TEXTURES if built_file(name).exists()]
    run([BLENDER, "-b", "--factory-startup", "--python", SHEET, "--", BUILD / "review.png", REVIEW_TILE,
         *[built_file(name) for name in present]])
    for i, name in enumerate(present, 1):
        print(f"  {i:>2} {name}")


def status():
    records = recorded()
    for name in TEXTURES:
        asset, digest = records.get(name, ("", ""))
        path = built_file(name)
        if not path.exists():
            state = "not built"
        elif not asset:
            state = "never uploaded"
        elif sha(path) != digest:
            state = "CHANGED since its upload: upload it again"
        else:
            state = "current"
        print(f"  {name:<14} {state}")
    for name in records:
        if name not in TEXTURES:
            print(f"  {name:<14} recorded but not in the registry: remove it")


def record(pairs):
    records = recorded()
    for pair in pairs:
        name, asset = pair.split("=", 1)
        assert name in TEXTURES, f"{name} isn't in the registry"
        path = built_file(name)
        assert path.exists(), f"{name} isn't built: run build first"
        asset = asset if asset.startswith("rbxassetid://") else f"rbxassetid://{asset}"
        records[name] = (asset, sha(path))
    write_luau(records)


def main():
    command, args = (sys.argv[1], sys.argv[2:]) if len(sys.argv) > 1 else ("status", [])
    {"build": lambda: build(args), "status": status, "record": lambda: record(args), "review": review}[command]()


if __name__ == "__main__":
    main()
